#!/usr/bin/env node
// build-agents.mjs — single-source boilerplate for expert agent prompts.
//
// Canonical block text lives in agents/shared/blocks/<name>.md. Agent files
// contain the same sections inline (small models must not need an extra read
// for mandatory rules). This script keeps them in sync:
//
//   --check    exit 1 listing every agent whose block section drifted (CI gate)
//   --fix      rewrite drifted sections to the canonical text
//   --compact  emit dist/compact-agents/<agent>.md with boilerplate sections
//              replaced by the .compact.md variants (for tier=small installs)
//   --build    (v2 only) emit EVERY agents/**/*.md, frontmatter-transformed, to dist/agents-v2/
//
// Target (WP-V1): --target opencode-v1|opencode-v2 (default opencode-v1, env ATTEST_TARGET).
// Sources stay V1-shaped. For opencode-v2 the frontmatter is rewritten per the v1->v2 migration
// guide: disable->disabled, prompt->system, permission->permissions, maxSteps->steps (mode is kept).
// Reference docs under agents/shared/ and agents/*/ carry `disable: true` so they never load as
// agents; under v2 they MUST come out `disabled: true` or they would. v2 outputs go to
// dist/agents-v2/ and dist/compact-agents-v2/ (generated by install.sh, not committed).
// NOTE: only the KEY is renamed; the VALUE shape of permission(s) is unverified (see manifest).
//
// Section matching is by exact heading; agents without a given heading are
// untouched. Edit blocks/, run --fix, commit — never edit the sections inline.

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { join, basename } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const AGENTS_DIR = join(ROOT, 'agents');
const BLOCKS_DIR = join(AGENTS_DIR, 'shared', 'blocks');
const TARGETS = ['opencode-v1', 'opencode-v2'];
const MODES = ['--check', '--fix', '--compact', '--build'];
const argv = process.argv.slice(2);
const tIdx = argv.indexOf('--target');
const TARGET = (tIdx !== -1 ? argv[tIdx + 1] : process.env.ATTEST_TARGET) || 'opencode-v1';
if (!TARGETS.includes(TARGET)) {
  console.error(`unknown --target "${TARGET}" (expected ${TARGETS.join(' | ')})`);
  process.exit(2);
}
const V2 = TARGET === 'opencode-v2';
const COMPACT_DIR = join(ROOT, 'dist', V2 ? 'compact-agents-v2' : 'compact-agents');
const V2_DIR = join(ROOT, 'dist', 'agents-v2');

// v1 -> v2 frontmatter key renames (top-level keys only; nested/indented lines are untouched).
const V2_RENAMES = { disable: 'disabled', prompt: 'system', permission: 'permissions', maxSteps: 'steps' };
function toV2Frontmatter(text) {
  if (!text.startsWith('---\n')) return text;
  const end = text.indexOf('\n---', 4);
  if (end === -1) return text;
  const fm = text.slice(0, end).split('\n').map((line) => {
    const m = line.match(/^([A-Za-z]\w*):(.*)$/);
    return m && V2_RENAMES[m[1]] ? `${V2_RENAMES[m[1]]}:${m[2]}` : line;
  }).join('\n');
  return fm + text.slice(end);
}
// A v2 file must not mix: any leftover v1-only key means the transform missed it.
const v1KeysIn = (text) => {
  if (!text.startsWith('---\n')) return [];
  const end = text.indexOf('\n---', 4);
  return text.slice(0, end === -1 ? 0 : end).split('\n').map((l) => (l.match(/^([A-Za-z]\w*):/) ?? [])[1]).filter((k) => k && V2_RENAMES[k]);
};

const BLOCKS = [
  { name: 'handoff-intake', heading: '## HANDOFF intake (MANDATORY — resolve before any other mode)' },
  { name: 'loop-prevention', heading: '## Loop prevention (MANDATORY)' },
  { name: 'context-budget', heading: '## Context Budget (MANDATORY for local models)' },
  { name: 'research-tools', heading: '## Research tools (available, optional)' },
  { name: 'code-search', heading: '## Code search (available, optional)' },
  { name: 'delta-review', heading: '## Delta review (MANDATORY when the HANDOFF names a prior report or the scan JSON has meta.scope=="incremental")' },
];

// (file, block) pairs allowed to keep custom text — orchestrator mode files own
// a deliberately compressed Context Budget phrased for phase-doc loading.
const VARIANT_OK = new Set([
  'sdlc-init-mode.md::context-budget',
  'sdlc-onboard-mode.md::context-budget',
  'sdlc-feature-mode.md::context-budget',
  'sdlc-improve-mode.md::context-budget',
]);

const mode = argv.find((a) => MODES.includes(a)) ?? '--check';
if (argv.some((a) => a.startsWith('--') && a !== '--target' && !MODES.includes(a))) {
  console.error('usage: build-agents.mjs --check | --fix | --compact | --build [--target opencode-v1|opencode-v2]');
  process.exit(2);
}
if (mode === '--build' && !V2) {
  console.log('--build is only needed for opencode-v2 (v1 installs agents/ as-is) — nothing to do');
  process.exit(0);
}

// Block files carry disable frontmatter so runtimes don't register them as
// agents — strip it before injection.
const loadBlock = (name, compact = false) => {
  let text = readFileSync(join(BLOCKS_DIR, `${name}${compact ? '.compact' : ''}.md`), 'utf8');
  if (text.startsWith('---\n')) {
    const end = text.indexOf('\n---\n', 4);
    if (end !== -1) text = text.slice(end + 5).replace(/^\n+/, '');
  }
  return text.trimEnd() + '\n';
};

// Replace the section under `heading` (up to the next ## or EOF) with `body`.
// Returns null when the heading is absent.
function replaceSection(text, heading, body) {
  const lines = text.split('\n');
  const start = lines.findIndex((l) => l === heading);
  if (start === -1) return null;
  let end = lines.length;
  for (let i = start + 1; i < lines.length; i++) {
    if (lines[i].startsWith('## ')) { end = i; break; }
  }
  // preserve exactly one blank line before the next section
  const replacement = body.trimEnd().split('\n');
  return [...lines.slice(0, start), ...replacement, '', ...lines.slice(end)].join('\n');
}

function currentSection(text, heading) {
  const lines = text.split('\n');
  const start = lines.findIndex((l) => l === heading);
  if (start === -1) return null;
  let end = lines.length;
  for (let i = start + 1; i < lines.length; i++) {
    if (lines[i].startsWith('## ')) { end = i; break; }
  }
  return lines.slice(start, end).join('\n').trimEnd() + '\n';
}

// Top-level agents/*.md are the primary agents. Cluster agents live in
// subdirectories (code-review/, security/, performance/, game/, sdlc/onboard/)
// and carry the same mandatory blocks, so --check/--fix must reach them too —
// otherwise a block edit propagates to the primaries only and the clusters keep
// silently stale text. agents/shared/ holds reference docs and block sources,
// never agents, so it is excluded.
function collectAgents(dir) {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) {
      if (e.name !== 'shared') out.push(...collectAgents(join(dir, e.name)));
    } else if (e.name.endsWith('.md')) {
      out.push(join(dir, e.name));
    }
  }
  return out;
}
const rel = (f) => f.slice(AGENTS_DIR.length + 1);

// --compact emits a FLAT dist/compact-agents/ that install.sh overlays onto
// agents/ by basename, so it stays top-level only.
const primaryAgentFiles = readdirSync(AGENTS_DIR)
  .filter((f) => f.endsWith('.md'))
  .map((f) => join(AGENTS_DIR, f));
// --build/--check(v2) also cover the reference docs in agents/shared/** (frontmatter `disable: true`).
function collectAllMd(dir) {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) out.push(...collectAllMd(join(dir, e.name)));
    else if (e.name.endsWith('.md')) out.push(join(dir, e.name));
  }
  return out;
}
const agentFiles = mode === '--compact' ? primaryAgentFiles : collectAgents(AGENTS_DIR);

let drifted = [];
let compacted = 0;

// v2 emit / validation over every markdown file under agents/ (includes shared/ reference docs).
let v2Built = 0;
const v2Problems = [];
if (V2 && (mode === '--build' || mode === '--check')) {
  for (const file of collectAllMd(AGENTS_DIR)) {
    const src = readFileSync(file, 'utf8');
    const out = toV2Frontmatter(src);
    const srcDisable = /^disable:/m.test(src.split('\n---')[0] ?? '');
    if (v1KeysIn(out).length) v2Problems.push(`${rel(file)}: v1-only key left after transform: ${v1KeysIn(out).join(', ')}`);
    if (srcDisable && !/^disabled:/m.test(out.split('\n---')[0])) v2Problems.push(`${rel(file)}: disable: did not become disabled:`);
    if (mode === '--build') {
      const dest = join(V2_DIR, file.slice(AGENTS_DIR.length + 1));
      mkdirSync(join(dest, '..'), { recursive: true });
      writeFileSync(dest, out);
      v2Built++;
    }
  }
  if (v2Problems.length) {
    console.log(`V2 FRONTMATTER PROBLEMS (${v2Problems.length}):`);
    for (const d of v2Problems) console.log('  ' + d);
    process.exit(1);
  }
  if (mode === '--build') {
    console.log(`v2 agents written: ${v2Built} → dist/agents-v2/`);
    process.exit(0);
  }
}

for (const file of agentFiles) {
  let text = readFileSync(file, 'utf8');

  if (mode === '--compact') {
    let out = text;
    let touched = false;
    for (const { name, heading } of BLOCKS) {
      const next = replaceSection(out, heading, loadBlock(name, true));
      if (next) { out = next; touched = true; }
    }
    if (touched) {
      mkdirSync(COMPACT_DIR, { recursive: true });
      writeFileSync(join(COMPACT_DIR, basename(file)), V2 ? toV2Frontmatter(out) : out);
      compacted++;
    }
    continue;
  }

  for (const { name, heading } of BLOCKS) {
    if (VARIANT_OK.has(`${basename(file)}::${name}`)) continue;
    const canonical = loadBlock(name);
    const current = currentSection(text, heading);
    if (current === null) continue;
    if (current !== canonical) {
      if (mode === '--fix') {
        text = replaceSection(text, heading, canonical);
        writeFileSync(file, text);
      }
      drifted.push(`${rel(file)} :: ${name}`);
    }
  }
}

if (mode === '--compact') {
  console.log(`compact variants written: ${compacted} → dist/${V2 ? 'compact-agents-v2' : 'compact-agents'}/`);
} else if (drifted.length) {
  console.log(`${mode === '--fix' ? 'fixed' : 'DRIFTED'} (${drifted.length}):`);
  for (const d of drifted) console.log('  ' + d);
  process.exit(mode === '--fix' ? 0 : 1);
} else {
  console.log(`all block sections in sync across ${agentFiles.length} agents${V2 ? ' (opencode-v2 frontmatter transform verified)' : ''}`);
}
